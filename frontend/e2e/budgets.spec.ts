import {signIn} from './auth';
import {test,expect} from '@playwright/test';

test('category budgets use posted spending, persist edits, copy safely and stay isolated',async({page},info)=>{
 await signIn(page);
 await expect(page.locator('.overview-hero')).toBeVisible();
 const created=await page.request.post('/api/workspaces',{headers:{'X-SF-Request':'1'},data:{name:'งบทดสอบ '+info.project.name+' '+Date.now()}});
 expect(created.ok()).toBe(true);const workspace=await created.json();
 const accountResponse=await page.request.get(`/api/workspaces/${workspace.id}/accounts`);const accounts=await accountResponse.json();
 const category=accounts.find((a:any)=>a.kind==='expense');const wallet=accounts.find((a:any)=>a.kind==='asset');
 const posted=await page.request.post(`/api/workspaces/${workspace.id}/transactions`,{headers:{'X-SF-Request':'1'},data:{kind:'expense',account_id:wallet.id,category_id:category.id,amount:7500,description:'ข้าวทดสอบงบ',occurred_on:'2026-10-11',idempotency_key:crypto.randomUUID()}});
 expect(posted.ok()).toBe(true);
 await page.goto('/services');
 const compact=(page.viewportSize()?.width||1440)<=900;
 const switcher=page.getByLabel(compact?'เลือก workspace บนมือถือ':'เลือก workspace',{exact:true});
 await switcher.selectOption(workspace.id);
 await expect(page.locator('.services-intro')).toBeVisible();
 await page.locator('.service-card').filter({has:page.getByRole('heading',{name:'งบประมาณ',exact:true})}).click();
 await expect(page.getByLabel(compact?'เลือก workspace บนมือถือ':'เลือก workspace',{exact:true})).toHaveValue(workspace.id);
 await expect(page.locator('.budget-empty')).toBeVisible();
 await page.getByRole('button',{name:'ตั้งงบหมวดแรก',exact:true}).click();
 const dialog=page.locator('dialog[open]');
 await dialog.getByLabel('หมวดของงบ').selectOption(category.id);
 await dialog.getByLabel('วงเงินงบประมาณ').fill('100.00');
 await dialog.getByRole('button',{name:'บันทึกวงเงิน',exact:true}).click();
 const card=page.locator('.budget-card').filter({hasText:category.name});
 await expect(card).toBeVisible();await expect(card).toContainText('฿75.00');await expect(card).toContainText('฿25.00');
 await page.getByRole('button',{name:'แก้งบ '+category.name,exact:true}).click();
 await dialog.getByLabel('วงเงินงบประมาณ').fill('70.00');await dialog.getByRole('button',{name:'บันทึกวงเงิน',exact:true}).click();
 await expect(card.locator('.budget-status')).toHaveText(/เกินงบ/);await expect(card).toContainText('฿5.00');
 await page.reload();await expect(page.getByLabel(compact?'เลือก workspace บนมือถือ':'เลือก workspace',{exact:true})).toHaveValue(workspace.id);
 await expect(card.locator('.budget-status')).toHaveText(/เกินงบ/);
 await page.screenshot({path:`../artifacts/budgets-${info.project.name}.png`,fullPage:true});
 await page.getByRole('button',{name:'เดือนถัดไป',exact:true}).click();await expect(page.locator('.budget-empty')).toBeVisible();
 await page.getByRole('button',{name:'ใช้วงเงินเดือนก่อน',exact:true}).click();await expect(card).toBeVisible();await expect(card.locator('.budget-used')).toContainText('฿0.00');
 await expect(card).toContainText('฿70.00');
 await page.getByRole('button',{name:'ใช้วงเงินเดือนก่อน',exact:true}).click();await expect(page.getByRole('status').filter({hasText:'ไม่มีวงเงินใหม่ให้คัดลอก'})).toBeVisible();
 await page.getByRole('button',{name:'นำงบ '+category.name+' ออก',exact:true}).click();
 await dialog.getByRole('button',{name:'ยืนยันนำวงเงินออก',exact:true}).click();await expect(page.locator('.budget-empty')).toBeVisible();
 const rows=await (await page.request.get(`/api/workspaces/${workspace.id}/transactions`)).json();expect(rows).toHaveLength(1);
 await page.getByLabel(compact?'เลือก workspace บนมือถือ':'เลือก workspace',{exact:true}).selectOption({index:0});
 await expect(page.locator('.budget-overview')).toBeVisible();
 await expect(page.locator('.budget-card')).toHaveCount(0);
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
