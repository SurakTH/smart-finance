import {signIn} from './auth';
import {test,expect} from '@playwright/test';

test('all services, focused account/category creation and mobile access',async({page},info)=>{
 await signIn(page);
 await expect(page.locator('.overview-hero')).toBeVisible();
 const compact=(page.viewportSize()?.width||1440)<=900;
 if(compact){
  await expect(page.locator('.bottom-nav a')).toHaveCount(5);
  await page.locator('.bottom-nav').getByRole('link',{name:'ทั้งหมด',exact:true}).click();
 }else await page.locator('.sidebar').getByRole('link',{name:'บริการทั้งหมด',exact:true}).click();
 await expect(page.getByRole('heading',{name:'บริการทั้งหมด',exact:true})).toBeVisible();
 await expect(page.locator('.service-card')).toHaveCount(15);
 await page.getByLabel('ค้นหาบริการ').fill('CSV');
 await page.locator('.service-card').filter({has:page.getByRole('heading',{name:'ส่งออกข้อมูล',exact:true})}).click();
 await expect(page.getByRole('button',{name:'ส่งออก CSV',exact:true})).toBeVisible();
 await page.goto('/services');
 await page.getByLabel('ค้นหาบริการ').fill('ไม่มีบริการนี้');
 await expect(page.getByRole('heading',{name:'ไม่พบบริการที่ค้นหา'})).toBeVisible();
 await page.getByRole('button',{name:'ล้างคำค้นหาบริการ'}).click();
 await page.locator('.service-card').filter({has:page.getByRole('heading',{name:'บัญชี',exact:true})}).click();
 await expect(page.getByRole('heading',{name:'บัญชี',exact:true})).toBeVisible();
 await expect(page.locator('#management-create select option')).toHaveText(['บัญชีเงิน / กระเป๋าเงิน','บัตรเครดิต / หนี้สิน']);
 const account='กระเป๋าทดสอบ '+info.project.name+' '+Date.now();
 await page.locator('.page-heading').getByRole('button',{name:'เพิ่มบัญชี',exact:true}).click();
 await expect(page.getByLabel('ชื่อบัญชี',{exact:true})).toBeFocused();
 await page.getByLabel('ชื่อบัญชี',{exact:true}).fill(account);
 await page.locator('#management-create').getByRole('button',{name:'เพิ่มบัญชี',exact:true}).click();
 await expect(page.locator('.account-grid')).toContainText(account);
 await page.locator('.management-switch').getByRole('link',{name:'หมวดหมู่',exact:true}).click();
 await expect(page.getByRole('heading',{name:'หมวดหมู่',exact:true})).toBeVisible();
 await expect(page.locator('#management-create select option')).toHaveText(['หมวดรายจ่าย','หมวดรายรับ']);
 await expect(page.locator('.category-grid')).not.toContainText(account);
 await page.getByRole('button',{name:/^หมวดรายรับ/}).click();
 await expect(page.locator('#management-create select')).toHaveValue('income');
 const category='รายรับทดสอบ '+info.project.name+' '+Date.now();
 await page.getByLabel('ชื่อหมวดหมู่',{exact:true}).fill(category);
 await page.locator('#management-create').getByRole('button',{name:'เพิ่มหมวดหมู่',exact:true}).click();
 await expect(page.locator('.category-grid')).toContainText(category);
 await page.locator('.category-tile').filter({hasText:category}).click();
 await expect(page).toHaveURL(/transactions\?category_id=.*&kind=income/);
 await expect(page.getByRole('button',{name:'รายรับ',exact:true})).toHaveAttribute('aria-pressed','true');
 await page.goto('/services');
 await page.locator('.service-card').filter({has:page.getByRole('heading',{name:'เชื่อม Telegram',exact:true})}).click();
 await expect(page.locator('#telegram-settings')).toBeInViewport();
 await page.goto('/services');
 await expect(page.locator('.service-card')).toHaveCount(15);
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.screenshot({path:`../artifacts/services-${info.project.name}.png`,fullPage:true});
 await page.goto('/categories');
 await expect(page.locator('.category-directory')).toBeVisible();
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.screenshot({path:`../artifacts/categories-${info.project.name}.png`,fullPage:true});
});
